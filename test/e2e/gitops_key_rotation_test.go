// Use case: a tenant admin rotates the tenant key through GitOps: the new key is generated by the
// operator or brought by the tenant admin, scripts/rotate.sh adds it to the files in the GitOps
// directory, the GitOps tool applies them, the operator completes the rotation, and scripts/rotate.sh
// removes the old key.
func TestGitOpsKeyRotation(t *testing.T) {
	t.Parallel()
	t.Run("shall rotate to a key the operator generates", func(t *testing.T) {
		t.Parallel()
		r := newGitOpsRepo(t, "e2e-gitops-rotate")
		t.Run("shall generate the new key when a rotation is started", func(t *testing.T) {
			update(t, r.tenant, func() { r.tenant.Spec.StartRotation = true })
			r.waitForRotated(t, sopsv1alpha1.ReasonRotationPending, r.inProgress)
			r.newKey = r.tenant.Status.PublicKey
		})
		r.rotateAndComplete(t)
	})
	t.Run("shall rotate to a key the tenant admin brings", func(t *testing.T) {
		t.Parallel()
		r := newGitOpsRepo(t, "e2e-gitops-bring")
		t.Run("shall wait for the tenant admin's key when a rotation is started", func(t *testing.T) {
			update(t, r.tenant, func() {
				r.tenant.Spec.GenerateKey = new(bool)
				r.tenant.Spec.StartRotation = true
			})
			r.waitForRotated(t, sopsv1alpha1.ReasonWaitingForKey, func() bool {
				return r.tenant.Status.Rotation != nil &&
					r.tenant.Status.Rotation.Phase == sopsv1alpha1.RotationPhaseWaitingForKey
			})
			if out, err := r.rotate(); err == nil || !strings.Contains(out, "waiting for its new key") {
				t.Fatalf("rotate.sh must ask to wait while the tenant waits for its key, got %v\n%s", err, out)
			}
		})
		t.Run("shall take the key the tenant admin puts into the key Secret", func(t *testing.T) {
			recipient := replaceKeySecret(t, r.tenantNS)
			r.waitForRotated(t, sopsv1alpha1.ReasonRotationPending, r.inProgress)
			if r.tenant.Status.PublicKey != recipient {
				t.Fatal("status.publicKey is not the key the tenant admin brought")
			}
			r.newKey = recipient
		})
		r.rotateAndComplete(t)
	})
}

// gitOpsRepo is a GitOps directory with the repo's .sops.yaml, the tenant and one SopsSecret file in each
// of two namespaces, applied to the cluster.
type gitOpsRepo struct {
	dir, sopsConfig, tenantFile, bin string
	tenantNS, oldKey, newKey         string
	tenant                           *sopsv1alpha1.SopsTenant
	files                            []string
	secrets                          []*sopsv1alpha1.SopsSecret
	values                           map[string]string
}

func newGitOpsRepo(t *testing.T, prefix string) *gitOpsRepo {
	t.Helper()
	prodA := namespace(t, prefix+"-a")
	prodB := namespace(t, prefix+"-b")
	tenantNS, oldKey := onboardedTenant(t, prefix, prodA, prodB)
	r := &gitOpsRepo{
		dir: t.TempDir(), bin: t.TempDir(), tenantNS: tenantNS, oldKey: oldKey,
		tenant: &sopsv1alpha1.SopsTenant{ObjectMeta: metav1.ObjectMeta{Name: tenantName, Namespace: tenantNS}},
		values: map[string]string{prodA: "password-a", prodB: "password-b"},
	}
	r.sopsConfig = filepath.Join(r.dir, ".sops.yaml")
	writeFile(t, r.sopsConfig, "creation_rules:\n  - path_regex: \\.sops\\.ya?ml$\n    age: "+oldKey+"\n")
	r.tenantFile = filepath.Join(r.dir, "tenant.yaml")
	tenantYAML := render(t, "sopstenant.yaml", map[string]any{"Name": tenantName, "Namespace": tenantNS})
	writeFile(t, r.tenantFile, string(tenantYAML))
	for _, ns := range []string{prodA, prodB} {
		obj := encryptSopsSecret(t, oldKey, sopsSecret{
			Name: "db-creds", Namespace: ns, Scope: ns + "/db-creds", TenantNamespace: tenantNS,
			StringData: map[string]string{"password": r.values[ns]},
		})
		out, err := yaml.Marshal(obj)
		if err != nil {
			t.Fatal(err)
		}
		file := filepath.Join(r.dir, ns, "db-creds.sops.yaml")
		writeFile(t, file, string(out))
		r.files = append(r.files, file)
		secret := &sopsv1alpha1.SopsSecret{ObjectMeta: metav1.ObjectMeta{Name: "db-creds", Namespace: ns}}
		r.secrets = append(r.secrets, secret)
	}
	writeFile(t, filepath.Join(r.bin, "oc"), "#!/usr/bin/env bash\nexec kubectl --context "+kubeContext+" \"$@\"\n")
	if err := os.Chmod(filepath.Join(r.bin, "oc"), 0o755); err != nil {
		t.Fatal(err)
	}
	r.applyFiles(t)
	return r
}

// applyFiles applies the SopsSecret files, as the GitOps tool does, and waits until they are decrypted.
func (r *gitOpsRepo) applyFiles(t *testing.T) {
	t.Helper()
	for _, f := range r.files {
		if out, err := kubectl("", "apply", "-f", f); err != nil {
			t.Fatalf("apply %s: %v\n%s", f, err, out)
		}
	}
	for _, s := range r.secrets {
		waitForCurrentGeneration(t, s)
	}
}

// rotate runs scripts/rotate.sh on the directory with oc answered by kubectl.
func (r *gitOpsRepo) rotate() (string, error) {
	cmd := exec.Command(filepath.Join(repoRoot(), "scripts", "rotate.sh"), r.tenantFile, r.dir)
	cmd.Env = append(os.Environ(), "PATH="+r.bin+":"+filepath.Dir(envOr("YQ", "yq"))+":"+os.Getenv("PATH"))
	out, err := cmd.CombinedOutput()
	return string(out), err
}

// mentions reports whether .sops.yaml or a SopsSecret file contains key.
func (r *gitOpsRepo) mentions(t *testing.T, key string) bool {
	t.Helper()
	for _, f := range append([]string{r.sopsConfig}, r.files...) {
		content, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		if strings.Contains(string(content), key) {
			return true
		}
	}
	return false
}

func (r *gitOpsRepo) waitForRotated(t *testing.T, reason string, ready func() bool) {
	t.Helper()
	rotated := func() *metav1.Condition {
		return meta.FindStatusCondition(r.tenant.Status.Conditions, sopsv1alpha1.ConditionRotated)
	}
	poll(t, "Rotated reason "+reason, func() (bool, error) {
		if err := k8s.Get(context.Background(), client.ObjectKeyFromObject(r.tenant), r.tenant); err != nil {
			return false, err
		}
		c := rotated()
		return c != nil && c.Reason == reason && ready(), nil
	}, func() string {
		if c := rotated(); c != nil {
			return "last Rotated: " + c.Reason + ": " + c.Message
		}
		return "no Rotated condition"
	})
}

// inProgress reports whether the tenant's new key is in place and the old one kept for the rotation.
func (r *gitOpsRepo) inProgress() bool {
	rot := r.tenant.Status.Rotation
	return rot != nil && rot.Phase == sopsv1alpha1.RotationPhaseInProgress && rot.PreviousPublicKey == r.oldKey &&
		r.tenant.Status.PublicKey != r.oldKey
}

// rotateAndComplete runs the rotation from the moment the new key is in place to the removal of the old key.
func (r *gitOpsRepo) rotateAndComplete(t *testing.T) {
	t.Run("shall back up the old and the new key during the rotation", func(t *testing.T) {
		if r.newKey == "" {
			t.Skip("needs the new key from the previous subtests")
		}
		both := []string{r.oldKey + "," + r.newKey, r.newKey + "," + r.oldKey}
		poll(t, "backups of the old and the new key", func() (bool, error) {
			keys := backedUpKeys(t, r.tenantNS)
			return keys == both[0] || keys == both[1], nil
		})
		for _, s := range r.secrets {
			poll(t, "the new key's entry of "+s.Namespace+"/"+s.Name, func() (bool, error) {
				if err := k8s.Get(context.Background(), client.ObjectKeyFromObject(s), s); err != nil {
					return false, err
				}
				rot := s.Status.Rotation
				return rot != nil && rot.NewRecipient != nil && rot.NewRecipient.Recipient == r.newKey, nil
			})
		}
	})

	t.Run("shall add the new key to the files with scripts/rotate.sh", func(t *testing.T) {
		if r.newKey == "" {
			t.Skip("needs the new key from the previous subtests")
		}
		if out, err := r.rotate(); err != nil {
			t.Fatalf("rotate.sh: %v\n%s", err, out)
		}
		config, err := os.ReadFile(r.sopsConfig)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(config), r.newKey) || !strings.Contains(string(config), r.oldKey) {
			t.Fatal(".sops.yaml must list the old and the new key during the rotation")
		}
	})

	t.Run("shall complete the rotation once the files are applied", func(t *testing.T) {
		if r.newKey == "" {
			t.Skip("needs the new key from the previous subtests")
		}
		r.applyFiles(t)
		update(t, r.tenant, func() { r.tenant.Spec.StartRotation = false })
		r.waitForRotated(t, sopsv1alpha1.ReasonRotationComplete, func() bool {
			last := r.tenant.Status.LastRotation
			return r.tenant.Status.Rotation == nil && last != nil && last.PreviousPublicKey == r.oldKey &&
				r.tenant.Status.PublicKey == r.newKey
		})
		ks, err := crypto.ParseKeyFile(tenantKey(t, r.tenantNS).Data[crypto.KeyFileField])
		if err != nil {
			t.Fatal(err)
		}
		if len(ks.Recipients) != 1 || ks.Recipients[0] != r.newKey {
			t.Fatalf("the key Secret must hold exactly the new key, got %d keys", len(ks.Recipients))
		}
		poll(t, "only the new key's backup to remain", func() (bool, error) {
			return backedUpKeys(t, r.tenantNS) == r.newKey, nil
		})
		r.assertValues(t)
		assertGolden(t, r.tenant, "rotated")
	})

	t.Run("shall remove the old key from the files with scripts/rotate.sh", func(t *testing.T) {
		if r.tenant.Status.LastRotation == nil {
			t.Skip("needs the completed rotation from the previous subtests")
		}
		if out, err := r.rotate(); err != nil {
			t.Fatalf("rotate.sh: %v\n%s", err, out)
		}
		if r.mentions(t, r.oldKey) {
			t.Fatal("the files or .sops.yaml still list the old key")
		}
		if !r.mentions(t, r.newKey) {
			t.Fatal("the files or .sops.yaml lost the new key")
		}
		r.applyFiles(t)
		r.assertValues(t)
	})
}

// assertValues checks that every output Secret still holds the value of its file.
func (r *gitOpsRepo) assertValues(t *testing.T) {
	t.Helper()
	for _, s := range r.secrets {
		waitForReason(t, s, sopsv1alpha1.ReasonDecrypted)
		if got := string(outputSecret(t, s.Namespace).Data["password"]); got != r.values[s.Namespace] {
			t.Fatalf("output Secret in %s changed its value", s.Namespace)
		}
	}
}

// replaceKeySecret replaces the tenant's key Secret with a new key, labelled for the operator, as a tenant
// admin who brings the key does, and returns the new key's recipient.
func replaceKeySecret(t *testing.T, tenantNamespace string) string {
	t.Helper()
	keyFile, recipient, err := crypto.GenerateKeyFile()
	if err != nil {
		t.Fatal(err)
	}
	deleteObject(t, tenantKey(t, tenantNamespace))
	brought := &corev1.Secret{
		ObjectMeta: metav1.ObjectMeta{
			Name: tenantKeySecret, Namespace: tenantNamespace,
			Labels: map[string]string{sopsv1alpha1.LabelEnabled: sopsv1alpha1.EnabledValue},
		},
		Data: map[string][]byte{crypto.KeyFileField: keyFile},
	}
	if err := k8s.Create(context.Background(), brought); apierrors.IsAlreadyExists(err) {
		key := tenantKey(t, tenantNamespace)
		update(t, key, func() { key.Labels, key.Data = brought.Labels, brought.Data })
	} else if err != nil {
		t.Fatalf("create the key Secret with the new key: %v", err)
	}
	return recipient
}

// backedUpKeys returns the public keys of the tenant's key backups, comma-separated in the order listed.
func backedUpKeys(t *testing.T, tenantNamespace string) string {
	t.Helper()
	backups := keyBackups(t, tenantNamespace)
	keys := make([]string, 0, len(backups))
	for _, b := range backups {
		keys = append(keys, b.Annotations[sopsv1alpha1.AnnotationPublicKey])
	}
	return strings.Join(keys, ",")
}

// waitForCurrentGeneration waits until the SopsSecret is Decrypted at its current generation.
func waitForCurrentGeneration(t *testing.T, s *sopsv1alpha1.SopsSecret) {
	t.Helper()
	poll(t, s.Namespace+"/"+s.Name+" to be Decrypted at its current generation", func() (bool, error) {
		if err := k8s.Get(context.Background(), client.ObjectKeyFromObject(s), s); err != nil {
			return false, client.IgnoreNotFound(err)
		}
		c := meta.FindStatusCondition(s.Status.Conditions, sopsv1alpha1.ConditionReady)
		return s.Status.ObservedGeneration == s.Generation && c != nil && c.Reason == sopsv1alpha1.ReasonDecrypted, nil
	})
}
